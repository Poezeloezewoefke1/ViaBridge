package dev.texturemixer.core.generate;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.texturemixer.core.TextureMixerConstants;
import dev.texturemixer.core.pack.SafePaths;
import dev.texturemixer.core.util.Log;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.DirectoryNotEmptyException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.StandardCopyOption;
import java.nio.file.attribute.BasicFileAttributes;

/**
 * Writes the generated pack as a folder pack.
 *
 * <p>Files are first written to a staging folder outside the resourcepacks directory
 * (so Minecraft never sees a half-written pack), then swapped into place. The target is
 * only ever replaced if it is missing or was itself generated by Texture Mixer: a folder
 * with the same name that lacks the marker is refused, so a player's own pack can never
 * be overwritten.
 */
public final class DirectoryPackWriter implements PackWriter {
    private final Path target;
    private final Path staging;
    private final Path previous;
    private boolean committed;

    public DirectoryPackWriter(Path target, Path workDirectory) throws IOException {
        this.target = target.toAbsolutePath().normalize();
        if (Files.exists(this.target) && !isGeneratedPack(this.target)) {
            throw new IOException("\"" + this.target.getFileName() + "\" already exists in the resource pack folder but was not created by Texture Mixer. Rename or move it, then try again.");
        }
        Files.createDirectories(workDirectory);
        this.staging = workDirectory.resolve("staging");
        this.previous = workDirectory.resolve("previous");
        deleteRecursively(staging);
        Files.createDirectories(staging);
    }

    /** Whether {@code folder} holds a pack.mcmeta with Texture Mixer's marker. */
    public static boolean isGeneratedPack(Path folder) {
        Path mcmeta = folder.resolve("pack.mcmeta");
        if (!Files.isRegularFile(mcmeta)) {
            return false;
        }
        try {
            JsonObject root = JsonParser.parseString(Files.readString(mcmeta, StandardCharsets.UTF_8)).getAsJsonObject();
            return root.has(TextureMixerConstants.MARKER_KEY);
        } catch (IOException | RuntimeException e) {
            return false;
        }
    }

    @Override
    public void write(String path, byte[] data) throws IOException {
        String safe = SafePaths.normalize(path);
        if (safe == null) {
            throw new IOException("Refusing to write unsafe path " + path);
        }
        Path file = staging.resolve(safe).normalize();
        if (!file.startsWith(staging)) {
            throw new IOException("Refusing to write outside the pack: " + path);
        }
        Files.createDirectories(file.getParent());
        Files.write(file, data);
    }

    @Override
    public void commit() throws IOException {
        Files.createDirectories(target.getParent());
        deleteRecursively(previous);
        if (Files.exists(target)) {
            if (!isGeneratedPack(target)) {
                throw new IOException("\"" + target.getFileName() + "\" was replaced by a pack not created by Texture Mixer; not overwriting it.");
            }
            move(target, previous);
        }
        try {
            move(staging, target);
        } catch (IOException e) {
            // Put the old pack back so the player is not left without one.
            if (Files.exists(previous) && !Files.exists(target)) {
                move(previous, target);
            }
            throw e;
        }
        deleteRecursively(previous);
        committed = true;
    }

    @Override
    public String describeTarget() {
        return target.toString();
    }

    @Override
    public void close() throws IOException {
        if (!committed) {
            deleteRecursively(staging);
        }
    }

    private static void move(Path from, Path to) throws IOException {
        try {
            Files.move(from, to, StandardCopyOption.ATOMIC_MOVE);
        } catch (AtomicMoveNotSupportedException | DirectoryNotEmptyException e) {
            // Different file systems: fall back to copy + delete.
            copyRecursively(from, to);
            deleteRecursively(from);
        }
    }

    private static void copyRecursively(Path from, Path to) throws IOException {
        Files.walkFileTree(from, new SimpleFileVisitor<>() {
            @Override
            public FileVisitResult preVisitDirectory(Path dir, BasicFileAttributes attrs) throws IOException {
                Files.createDirectories(to.resolve(from.relativize(dir).toString()));
                return FileVisitResult.CONTINUE;
            }

            @Override
            public FileVisitResult visitFile(Path file, BasicFileAttributes attrs) throws IOException {
                Files.copy(file, to.resolve(from.relativize(file).toString()), StandardCopyOption.REPLACE_EXISTING);
                return FileVisitResult.CONTINUE;
            }
        });
    }

    static void deleteRecursively(Path path) throws IOException {
        if (!Files.exists(path)) {
            return;
        }
        Files.walkFileTree(path, new SimpleFileVisitor<>() {
            @Override
            public FileVisitResult visitFile(Path file, BasicFileAttributes attrs) throws IOException {
                Files.delete(file);
                return FileVisitResult.CONTINUE;
            }

            @Override
            public FileVisitResult postVisitDirectory(Path dir, IOException exc) throws IOException {
                if (exc != null) {
                    throw exc;
                }
                Files.delete(dir);
                return FileVisitResult.CONTINUE;
            }
        });
        Log.LOGGER.debug("Deleted {}", path);
    }
}
